// Package fixtures provides deployment/market test fixtures typed against
// the currently-active module versions (deployment/v1beta5, market/v2beta1).
//
// pkg.akt.dev/go/testutil still generates deployment/v1beta4 groups and
// resource units. The v1beta5 types are a pure superset (the added AEP-87
// fields are nullable and default-empty), so this package re-builds the
// generated fixtures field-by-field into the new types and re-exports the
// version-agnostic helpers unchanged. Collapse this package back into direct
// pkg.akt.dev/go/testutil usage once its generators emit v1beta5 natively.
package fixtures

import (
	"math/rand"
	"testing"

	dv1 "pkg.akt.dev/go/node/deployment/v1"
	dvbeta "pkg.akt.dev/go/node/deployment/v1beta5"
	"pkg.akt.dev/go/testutil"
)

// Version-agnostic helpers, re-exported unchanged.
var (
	AccAddress            = testutil.AccAddress
	ACTCoin               = testutil.ACTCoin
	ACTDecCoinRandom      = testutil.ACTDecCoinRandom
	AkashCoin             = testutil.AkashCoin
	AkashDecCoinRandom    = testutil.AkashDecCoinRandom
	BidID                 = testutil.BidID
	DecCoin               = testutil.DecCoin
	DefaultDeploymentHash = testutil.DefaultDeploymentHash
	Deployment            = testutil.Deployment
	DeploymentID          = testutil.DeploymentID
	EnsureEvent           = testutil.EnsureEvent
	GroupID               = testutil.GroupID
	LeaseID               = testutil.LeaseID
	OrderID               = testutil.OrderID
	ResourceUnits         = testutil.ResourceUnits
	WithDenom             = testutil.WithDenom
)

// ResourceOption mirrors the option type accepted by Resources.
type ResourceOption = testutil.ResourceOption

// Resources generates a set of random resource units typed against
// deployment/v1beta5.
func Resources(t testing.TB, opts ...ResourceOption) dvbeta.ResourceUnits {
	t.Helper()

	from := testutil.Resources(t, opts...)

	res := make(dvbeta.ResourceUnits, 0, len(from))
	for _, unit := range from {
		res = append(res, dvbeta.ResourceUnit{
			Resources: unit.Resources,
			Count:     unit.Count,
			Price:     unit.Price,
		})
	}

	return res
}

// GroupSpec generates a random deployment/v1beta5 group spec.
func GroupSpec(t testing.TB) dvbeta.GroupSpec {
	t.Helper()

	return dvbeta.GroupSpec{
		Name:         testutil.Name(t, "dgroup"),
		Requirements: testutil.PlacementRequirements(t),
		Resources:    Resources(t),
	}
}

// DeploymentGroup generates a deployment/v1beta5 group in state `GroupOpen`
// with a set of random required attributes.
func DeploymentGroup(t testing.TB, did dv1.DeploymentID, gseq uint32) dvbeta.Group {
	t.Helper()

	return dvbeta.Group{
		ID:        dv1.MakeGroupID(did, gseq),
		State:     dvbeta.GroupOpen,
		GroupSpec: GroupSpec(t),
	}
}

// DeploymentGroups returns a set of deployment groups generated by
// DeploymentGroup.
func DeploymentGroups(t testing.TB, did dv1.DeploymentID, gseq uint32) dvbeta.Groups {
	t.Helper()

	count := rand.Intn(5) + 5 // nolint:gosec

	vals := make(dvbeta.Groups, 0, count)
	for i := 0; i < count; i++ {
		vals = append(vals, DeploymentGroup(t, did, gseq+uint32(i))) // nolint: gosec
	}

	return vals
}
